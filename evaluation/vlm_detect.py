"""Zero-shot detection with vision-language models: one forward pass per image, no generation.

    python vlm_detect.py --model qwen3vl_8b --manifest m.json --subset test --out scores_vlm_test --shard 0/7
    python vlm_detect.py --list

Each image is shown with PROMPT; the score is P(fake) from the next-token distribution, restricted to the
answer words: score = p(fake) / (p(fake) + p(real)), summing the variants in ANSWERS. pred = score >= 0.5.
`mass` = p(fake) + p(real) is written too: if it is low the model wanted to answer something else.
Images are downscaled so the long side is at most --max-side (same for every model) before the processor.
Output and resume as detect.py: <out>/<model>[.shard<i>of<n>].csv with id, score, pred, mass; score.py reads it.
Run it in the css-vlm image (Containerfile.vlm); the weights go to the HF cache in $CSS_WEIGHTS.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

from PIL import Image

import css_data as data

PROMPT = ("Is this image a real photograph, or was it generated by AI? "
          "Answer with exactly one word: real or fake.")
ANSWERS = {"real": ["real", "Real", " real", " Real"], "fake": ["fake", "Fake", " fake", " Fake"]}

# name: (Hugging Face repo, loader). Checked on the Hub before the run; see README for the choices.
MODELS = {
    "qwen3vl_8b": ("Qwen/Qwen3-VL-8B-Instruct", "auto"),
    "qwen3vl_30b_a3b": ("Qwen/Qwen3-VL-30B-A3B-Instruct", "auto"),
    "qwen25vl_7b": ("Qwen/Qwen2.5-VL-7B-Instruct", "auto"),
    "qwen25vl_32b": ("Qwen/Qwen2.5-VL-32B-Instruct", "auto"),
    "internvl3_8b": ("OpenGVLab/InternVL3-8B-Instruct", "internvl_chat"),
    "internvl35_30b_a3b": ("OpenGVLab/InternVL3_5-30B-A3B-HF", "auto"),
    "kimivl_a3b": ("moonshotai/Kimi-VL-A3B-Instruct", "remote"),
}


def copies_via_cpu():
    """On this server direct GPU-to-GPU copies (P2P) come back corrupted (checked: a 4096x4096 tensor sent
    0 -> 1 -> 0 differs by up to 5.3, the same through the CPU is exact). Models split over several GPUs then
    output garbage, so every cuda -> other cuda move goes through host memory."""
    import torch
    orig_to = torch.Tensor.to

    def target(args, kwargs):
        d = kwargs.get("device", args[0] if args else None)
        if isinstance(d, (str, int)):
            try:
                d = torch.device(d if isinstance(d, str) else f"cuda:{d}")
            except RuntimeError:
                return None
        return d if isinstance(d, torch.device) else None

    def to(self, *args, **kwargs):
        d = target(args, kwargs)
        if d is not None and self.is_cuda and d.type == "cuda" and d.index is not None and d.index != self.device.index:
            return orig_to(orig_to(self, "cpu"), *args, **kwargs)
        return orig_to(self, *args, **kwargs)

    torch.Tensor.to = to


class VLM:
    def __init__(self, name, debug=False):
        self.debug = debug
        import torch
        from transformers import AutoProcessor
        repo, loader = MODELS[name]
        if torch.cuda.device_count() > 1:
            copies_via_cpu()
        major = torch.cuda.get_device_capability(0)[0] if torch.cuda.is_available() else 0
        self.dtype = torch.bfloat16 if major >= 8 else torch.float16  # no bf16 before Ampere
        self.loader = loader
        if loader == "internvl_chat":
            self._load_internvl(repo)
            return
        remote = loader == "remote"
        self.processor = AutoProcessor.from_pretrained(repo, trust_remote_code=remote)
        if remote:
            from transformers import AutoModelForCausalLM as Auto
        else:
            from transformers import AutoModelForImageTextToText as Auto
        self.model = Auto.from_pretrained(repo, torch_dtype=self.dtype, device_map="auto",
                                          trust_remote_code=remote).eval()
        self._answer_ids(self.processor.tokenizer)

    def _answer_ids(self, tok):
        self.ids = {k: sorted({tok.encode(w, add_special_tokens=False)[0] for w in ws}) for k, ws in ANSWERS.items()}

    def _load_internvl(self, repo):
        """InternVL3 released only as remote code (no -hf weights): the model card's model.chat(), whose
        prompt (conversation template, <img><IMG_CONTEXT>*n</img>) is kept; generate() is wrapped to stop after
        one token and keep its logits."""
        from types import SimpleNamespace
        from transformers import AutoModel, AutoTokenizer
        tok = AutoTokenizer.from_pretrained(repo, trust_remote_code=True, use_fast=False)
        self.processor = SimpleNamespace(tokenizer=tok)
        self.model = AutoModel.from_pretrained(repo, torch_dtype=self.dtype, low_cpu_mem_usage=True,
                                               trust_remote_code=True, device_map="auto").eval()
        self._answer_ids(tok)
        generate, self._first = self.model.generate, None

        def first_token(*args, **kwargs):
            kwargs.update(max_new_tokens=1, do_sample=False, output_scores=True, return_dict_in_generate=True)
            out = generate(*args, **kwargs)
            self._first = out.scores[0][0]
            return out.sequences

        self.model.generate = first_token

    def _internvl_score_logits(self, img):
        """Model card load_image: dynamic tiling to 448x448 (max 12 tiles + thumbnail), ImageNet norm."""
        import torch
        import torchvision.transforms as T
        from torchvision.transforms.functional import InterpolationMode
        tf = T.Compose([T.Resize((448, 448), interpolation=InterpolationMode.BICUBIC), T.ToTensor(),
                        T.Normalize((0.485, 0.456, 0.406), (0.229, 0.224, 0.225))])
        tiles = dynamic_preprocess(img, image_size=448, use_thumbnail=True, max_num=12)
        pv = torch.stack([tf(t) for t in tiles]).to(self.dtype).to(self.model.device)
        with torch.no_grad():
            self.model.chat(self.processor.tokenizer, pv, "<image>\n" + PROMPT, dict(max_new_tokens=1))
        return self._first.float()

    def inputs(self, img):
        messages = [{"role": "user", "content": [{"type": "image", "image": img}, {"type": "text", "text": PROMPT}]}]
        try:
            return self.processor.apply_chat_template(messages, add_generation_prompt=True, tokenize=True,
                                                      return_dict=True, return_tensors="pt")
        except (TypeError, ValueError, KeyError):  # processors whose template takes the image separately
            text = self.processor.apply_chat_template(
                [{"role": "user", "content": [{"type": "image", "image": ""}, {"type": "text", "text": PROMPT}]}],
                add_generation_prompt=True, tokenize=False)
            return self.processor(text=text, images=img, return_tensors="pt")

    def score(self, img):
        import torch
        if self.loader == "internvl_chat":
            logits, x = self._internvl_score_logits(img), None
        else:
            x = self.inputs(img).to(self.model.device)
            x = {k: v.to(self.dtype) if torch.is_floating_point(v) else v for k, v in x.items()}
            with torch.no_grad():
                logits = self.model(**x).logits[0, -1].float()
        p = torch.softmax(logits, -1)
        if self.debug and x is not None:
            ids = [t for t in x["input_ids"][0].tolist() if t != x["input_ids"][0][0] or True]
            text = self.processor.tokenizer.decode(ids)
            print("prompt:", repr(text[:150] + " ... " + text[-200:]), "nan:", bool(torch.isnan(logits).any()), flush=True)
            top = torch.topk(p, 5)
            print("top5:", [(self.processor.tokenizer.decode([i]), round(v, 4))
                            for v, i in zip(top.values.tolist(), top.indices.tolist())], flush=True)
        pf, pr = p[self.ids["fake"]].sum().item(), p[self.ids["real"]].sum().item()
        return pf / (pf + pr) if pf + pr > 0 else 0.5, pf + pr


def dynamic_preprocess(image, min_num=1, max_num=12, image_size=448, use_thumbnail=False):
    """InternVL model card: split the image into tiles of image_size on the closest aspect-ratio grid."""
    w, h = image.size
    aspect = w / h
    ratios = sorted({(i, j) for n in range(min_num, max_num + 1) for i in range(1, n + 1) for j in range(1, n + 1)
                     if min_num <= i * j <= max_num}, key=lambda x: x[0] * x[1])
    best, best_diff, area = (1, 1), float("inf"), w * h
    for r in ratios:  # find_closest_aspect_ratio
        diff = abs(aspect - r[0] / r[1])
        if diff < best_diff:
            best_diff, best = diff, r
        elif diff == best_diff and area > 0.5 * image_size * image_size * r[0] * r[1]:
            best = r
    tw, th = image_size * best[0], image_size * best[1]
    resized = image.resize((tw, th))
    tiles = [resized.crop(((i % (tw // image_size)) * image_size, (i // (tw // image_size)) * image_size,
                           ((i % (tw // image_size)) + 1) * image_size, ((i // (tw // image_size)) + 1) * image_size))
             for i in range(best[0] * best[1])]
    if use_thumbnail and len(tiles) != 1:
        tiles.append(image.resize((image_size, image_size)))
    return tiles


def shrink(img, side):
    w, h = img.size
    s = side / max(w, h)
    return img if s >= 1 else img.resize((round(w * s), round(h * s)), Image.BICUBIC)


def run(name, manifest, out_dir, root=None, split=1.0, shard="0/1", subset=None, max_side=1024, limit=None,
        image_dir=None, debug=False, seed=0, retry_failed=False):
    import random
    import numpy as np
    import torch
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    rows = data.load(manifest, root, split, subset=subset, image_dir=image_dir)
    i, n = map(int, shard.split("/"))
    rows = rows[i::n][:limit]
    suffix = "" if n == 1 else f".shard{i}of{n}"
    out = Path(out_dir).resolve() / f"{name}{suffix}.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    done = set()
    if out.exists():
        with open(out, newline="", encoding="utf-8") as f:
            old = list(csv.DictReader(f))
        if retry_failed:  # drop the failed images (empty score) so they are run again
            old = [r for r in old if r["score"] != ""]
            with open(out, "w", newline="", encoding="utf-8") as f:
                w = csv.writer(f)
                w.writerow(["id", "score", "pred", "mass"])
                w.writerows([[r["id"], r["score"], r["pred"], r["mass"]] for r in old])
        done = {r["id"] for r in old}
    todo = [r for r in rows if r["id"] not in done]
    vlm = VLM(name, debug)
    print(f"{name}: dtype {vlm.dtype}, answer token ids {vlm.ids}", flush=True)
    new = not out.exists()
    with open(out, "a", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["id", "score", "pred", "mass"])
        for k, r in enumerate(todo):
            try:
                s, mass = vlm.score(shrink(Image.open(r["path"]).convert("RGB"), max_side))
                w.writerow([r["id"], s, int(s >= 0.5), round(mass, 4)])
            except Exception as e:  # noqa: BLE001  one bad image must not stop the run
                print(f"{name}: failed on {r['id']}: {type(e).__name__}: {e}", flush=True)
                w.writerow([r["id"], "", "", ""])
            f.flush()
            if k % 500 == 0:
                print(f"{name}: {k + 1}/{len(todo)}", flush=True)
    return out


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model")
    p.add_argument("--manifest")
    p.add_argument("--root", default=None)
    p.add_argument("--split", type=float, default=1.0)
    p.add_argument("--image-dir", default=None, help="flat folder with all the images (overrides --root)")
    p.add_argument("--subset", default=None)
    p.add_argument("--out", default="scores_vlm")
    p.add_argument("--shard", default="0/1")
    p.add_argument("--max-side", type=int, default=1024)
    p.add_argument("--limit", type=int, default=None, help="only the first N images of the shard (tests)")
    p.add_argument("--seed", type=int, default=0, help="seed of python, numpy and torch")
    p.add_argument("--retry-failed", action="store_true", help="run again the images written with an empty score")
    p.add_argument("--debug", action="store_true", help="print the 5 most likely next tokens per image")
    p.add_argument("--list", action="store_true")
    a = p.parse_args(argv)
    if a.list:
        for k, (repo, _) in MODELS.items():
            print(f"{k:20s} {repo}")
        return
    if not (a.model and a.manifest):
        p.error("--model and --manifest are required")
    print(run(a.model, a.manifest, a.out, a.root, a.split, a.shard, a.subset, a.max_side, a.limit,
              a.image_dir, a.debug, a.seed, a.retry_failed))


if __name__ == "__main__":
    main()
